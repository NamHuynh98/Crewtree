import { spawnSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { appDir, binPath, bundleRoot, crewtreeDir, currentLink, files, isInstalled, isWindows } from './layout.js';
import { health, stopServer } from './server.js';
import { c, CliError, confirm, fail, info, ok, warn } from './ui.js';

const LAUNCHD_LABEL = 'dev.crewtree.server';
const TASK_NAME = 'Crewtree';
const SYSTEMD_UNIT = 'crewtree.service';

function launchdPlist(): string {
  return path.join(os.homedir(), 'Library', 'LaunchAgents', `${LAUNCHD_LABEL}.plist`);
}
function xdgConfig(): string {
  return process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config');
}
function systemdUnit(): string {
  return path.join(xdgConfig(), 'systemd', 'user', SYSTEMD_UNIT);
}
function desktopEntry(): string {
  return path.join(xdgConfig(), 'autostart', 'crewtree.desktop');
}
/** What autostart runs at login: a small script that finds Node then (PLAN.md 16.3) */
export function autostartLauncher(): string {
  return path.join(crewtreeDir(), isWindows ? 'autostart.cmd' : 'autostart.sh');
}

/** The CLI through `current`, so updates apply without touching autostart. */
function autostartCli(): string {
  const root = isInstalled() ? currentLink() : bundleRoot();
  return path.join(root, 'cli', 'dist', 'index.js');
}

function run(cmd: string, args: string[]) {
  return spawnSync(cmd, args, { stdio: 'pipe', encoding: 'utf8', shell: false });
}

const shQuote = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

/**
 * The login launcher. Node is looked up at every login, not frozen at `autostart on`: people upgrade Node,
 * switch it with nvm / fnm / volta / mise, or install it with Homebrew, apt or the nodejs.org installer.
 */
function writeLauncher() {
  const file = autostartLauncher();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const cli = autostartCli();
  const customDir = process.env.CREWTREE_DIR;
  if (isWindows) {
    const lines = [
      '@echo off',
      'rem Generated by `crewtree autostart on`: finds Node at each login, then starts Crewtree in the background',
      ...(customDir ? [`set "CREWTREE_DIR=${customDir}"`] : []),
      `set "NODE=${process.execPath}"`,
      'if not exist "%NODE%" set "NODE="',
      'if not defined NODE for /f "delims=" %%i in (\'where node 2^>nul\') do if not defined NODE set "NODE=%%i"',
      `if not defined NODE if exist "%ProgramFiles%\\nodejs\\node.exe" set "NODE=%ProgramFiles%\\nodejs\\node.exe"`,
      `if not defined NODE (echo Crewtree autostart: Node.js not found>>"${files.serverLog()}" & exit /b 1)`,
      `"%NODE%" "${cli}" serve --detach`,
      '',
    ];
    fs.writeFileSync(file, lines.join('\r\n'));
    return file;
  }
  const home = os.homedir();
  const extraPath = [
    path.dirname(process.execPath),
    `${home}/.volta/bin`,
    `${home}/.local/share/mise/shims`,
    `${home}/.asdf/shims`,
    `${home}/.local/bin`,
    '/opt/homebrew/bin',
    '/usr/local/bin',
    '/usr/bin',
    '/bin',
  ];
  fs.writeFileSync(
    file,
    `#!/bin/sh
# Generated by \`crewtree autostart on\`: finds Node 22+ at each login, then runs Crewtree in the foreground
# for launchd / systemd. Run \`crewtree autostart on\` again to regenerate it.
PATH=${shQuote(process.env.PATH ?? '')}:${shQuote(extraPath.join(':'))}
export PATH
export NODE_ENV=production
${customDir ? `export CREWTREE_DIR=${shQuote(customDir)}\n` : ''}usable() { [ -n "$1" ] && [ -x "$1" ] && "$1" -e 'process.exit(+process.versions.node.split(".")[0] >= 22 ? 0 : 1)' 2>/dev/null; }
for node in ${shQuote(process.execPath)} "$(command -v node 2>/dev/null)" \\
  $(ls -r "$HOME"/.nvm/versions/node/*/bin/node "$HOME"/.local/share/fnm/node-versions/*/installation/bin/node 2>/dev/null); do
  if usable "$node"; then exec "$node" ${shQuote(cli)} serve; fi
done
echo "Crewtree autostart: Node.js 22 or newer not found (PATH=$PATH)" >&2
exit 1
`,
    { mode: 0o755 }
  );
  return file;
}

function linuxAutostart(mode: 'on' | 'off') {
  const unit = systemdUnit();
  const desktop = desktopEntry();
  if (mode === 'off') {
    if (fs.existsSync(unit)) {
      run('systemctl', ['--user', 'disable', '--now', SYSTEMD_UNIT]);
      fs.rmSync(unit, { force: true });
      run('systemctl', ['--user', 'daemon-reload']);
    }
    fs.rmSync(desktop, { force: true });
    fs.rmSync(autostartLauncher(), { force: true });
    ok('Autostart off');
    return;
  }
  const launcher = writeLauncher();
  // systemd user service where there is a user session bus; otherwise the XDG desktop autostart
  if (run('systemctl', ['--user', 'show-environment']).status === 0) {
    fs.mkdirSync(path.dirname(unit), { recursive: true });
    const esc = (s: string) => s.replace(/%/g, '%%').replace(/"/g, '\\"');
    fs.writeFileSync(
      unit,
      `[Unit]
Description=Crewtree (multi-agent orchestration for Claude Code)
After=network.target

[Service]
ExecStart=/bin/sh "${esc(launcher)}"
Restart=on-failure
RestartSec=5

[Install]
WantedBy=default.target
`
    );
    run('systemctl', ['--user', 'daemon-reload']);
    const res = run('systemctl', ['--user', 'enable', '--now', SYSTEMD_UNIT]);
    if (res.status !== 0) throw new CliError(`systemctl failed: ${(res.stderr || res.stdout).trim()}`);
    ok(`Autostart on (systemd user service ${SYSTEMD_UNIT})`);
    info(c.dim('To start it at boot without logging in: loginctl enable-linger'));
    return;
  }
  if (fs.existsSync('/proc/version') && /microsoft/i.test(fs.readFileSync('/proc/version', 'utf8'))) {
    fs.rmSync(launcher, { force: true });
    throw new CliError(
      'WSL without systemd has no login autostart',
      'Enable systemd in /etc/wsl.conf ([boot] systemd=true), or add `crewtree --no-open` to your shell profile.'
    );
  }
  fs.mkdirSync(path.dirname(desktop), { recursive: true });
  const quoted = `"${launcher.replace(/(["`$\\])/g, '\\$1')}"`;
  fs.writeFileSync(
    desktop,
    `[Desktop Entry]
Type=Application
Name=Crewtree
Comment=Multi-agent orchestration for Claude Code
Exec=/bin/sh ${quoted}
Terminal=false
X-GNOME-Autostart-enabled=true
`
  );
  ok(`Autostart on (${desktop}, at desktop login)`);
}

export function autostartEnabled(): boolean {
  if (process.platform === 'darwin') return fs.existsSync(launchdPlist());
  if (isWindows) return run('schtasks', ['/Query', '/TN', TASK_NAME]).status === 0;
  return fs.existsSync(systemdUnit()) || fs.existsSync(desktopEntry());
}

function autostartLabel(): string {
  if (process.platform === 'darwin') return launchdPlist();
  if (isWindows) return 'Task Scheduler entry "Crewtree"';
  return fs.existsSync(systemdUnit()) ? systemdUnit() : desktopEntry();
}

/** `crewtree autostart on|off`: launchd (macOS), Task Scheduler at logon (Windows), systemd / XDG (Linux). */
export function autostart(mode: 'on' | 'off') {
  if (process.platform === 'darwin') {
    const plist = launchdPlist();
    const uid = process.getuid?.() ?? 0;
    if (mode === 'off') {
      run('launchctl', ['bootout', `gui/${uid}/${LAUNCHD_LABEL}`]);
      fs.rmSync(plist, { force: true });
      fs.rmSync(autostartLauncher(), { force: true });
      ok('Autostart off');
      return;
    }
    const launcher = writeLauncher();
    fs.mkdirSync(path.dirname(plist), { recursive: true });
    fs.mkdirSync(files.logs(), { recursive: true });
    const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
    fs.writeFileSync(
      plist,
      `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${LAUNCHD_LABEL}</string>
  <key>ProgramArguments</key>
  <array><string>/bin/sh</string><string>${esc(launcher)}</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>
  <key>ThrottleInterval</key><integer>30</integer>
  <key>StandardOutPath</key><string>${esc(files.serverLog())}</string>
  <key>StandardErrorPath</key><string>${esc(files.serverLog())}</string>
</dict>
</plist>
`
    );
    run('launchctl', ['bootout', `gui/${uid}/${LAUNCHD_LABEL}`]);
    const res = run('launchctl', ['bootstrap', `gui/${uid}`, plist]);
    if (res.status !== 0)
      warn(`launchctl: ${res.stderr.trim() || 'could not load the agent now; it starts at next login'}`);
    ok(`Autostart on (${plist})`);
    return;
  }
  if (isWindows) {
    if (mode === 'off') {
      run('schtasks', ['/Delete', '/F', '/TN', TASK_NAME]);
      fs.rmSync(autostartLauncher(), { force: true });
      ok('Autostart off');
      return;
    }
    const launcher = writeLauncher();
    const res = run('schtasks', [
      '/Create',
      '/F',
      '/SC',
      'ONLOGON',
      '/RL',
      'LIMITED',
      '/TN',
      TASK_NAME,
      '/TR',
      `"${launcher}"`,
    ]);
    if (res.status !== 0) throw new CliError(`schtasks failed: ${(res.stderr || res.stdout).trim()}`);
    ok('Autostart on (Task Scheduler: Crewtree, at logon)');
    return;
  }
  linuxAutostart(mode);
}

/** `crewtree uninstall [--purge]`: lists what goes, asks, keeps data unless --purge (PLAN.md 16.3). */
export async function uninstall(opts: { purge?: boolean; yes?: boolean }) {
  const items: string[] = [];
  if (fs.existsSync(appDir())) items.push(`${appDir()}  (installed versions)`);
  if (fs.existsSync(binPath())) items.push(`${binPath()}  (crewtree command)`);
  if (autostartEnabled()) items.push(autostartLabel());
  if (opts.purge) items.push(`${crewtreeDir()}  (database, sessions, Crewtree agents, uploads, logs)`);
  if (!items.length) {
    ok('Nothing to uninstall');
    return;
  }
  console.log('This removes:');
  for (const i of items) info(`- ${i}`);
  if (!opts.purge)
    info(c.dim(`Your data in ${crewtreeDir()} is kept (use --purge to remove it). ~/.claude is never touched.`));
  if (!opts.yes && !(await confirm('Continue?'))) {
    fail('Cancelled');
    return;
  }
  if (await health()) await stopServer();
  if (autostartEnabled()) autostart('off');
  fs.rmSync(binPath(), { force: true });
  fs.rmSync(appDir(), { recursive: true, force: true });
  if (opts.purge) fs.rmSync(crewtreeDir(), { recursive: true, force: true });
  ok('Crewtree was uninstalled');
  if (isWindows) info(`Remove ${path.dirname(binPath())} from your user PATH if you added it.`);
  else info(`Remove the PATH line for ~/.local/bin from your shell profile if you added it only for Crewtree.`);
}

